/* ───────── TEXT NORMALIZATION ───────── */

function normalizeText(text) {

  return text

    .toLowerCase()

    .normalize('NFD')

    .replace(/[\u0300-\u036f]/g, '')

    .replace(/ä/g, 'a')

    .replace(/ö/g, 'o')

    .replace(/ü/g, 'u')

    .replace(/ß/g, 'ss');

}

