function renderGlossary(data, isSearch = false) {

  glossaryContainer.innerHTML = '';

  /* ───────── SUCHMODUS ───────── */

  if (isSearch) {

    data.forEach(entry => {

      const article =

        document.createElement('article');

      article.classList.add('glossary-entry');

      article.innerHTML = `

        <p class="glossary-text">

          <span class="glossary-term">

            ${entry.term}:

          </span>

          ${entry.description}

        </p>

      `;

      glossaryContainer.appendChild(article);

    });

    return;

  }

  /* ───────── NORMALES GLOSSAR ───────── */

  const grouped = {};

  data.forEach(item => {

    // const letter =
    //   item.term.charAt(0).toUpperCase();

    let letter =
      item.term.charAt(0).toUpperCase();

    /* ───────── UMLAUTE NORMALISIEREN ───────── */

    if (letter === 'Ä') letter = 'A';
    if (letter === 'Ö') letter = 'O';
    if (letter === 'Ü') letter = 'U';
    if (!grouped[letter]) {

      grouped[letter] = [];

    }

    grouped[letter].push(item);

  });

  Object.keys(grouped)

    .sort()

    .forEach(letter => {

      const section =

        document.createElement('section');

      section.classList.add('letter-section');

      section.id =

        letter.toLowerCase();

      section.innerHTML = `

        <div class="letter-marker">

          ${letter}

          <span class="letter-arrow">

            →

          </span>

        </div>

      `;

      grouped[letter].forEach(entry => {

        const article =

          document.createElement('article');

        article.classList.add('glossary-entry');

        article.innerHTML = `

          <p class="glossary-text">

            <span class="glossary-term">

              ${entry.term}:

            </span>

            ${entry.description}

          </p>

        `;

        section.appendChild(article);

      });

      glossaryContainer.appendChild(section);

    });

}



